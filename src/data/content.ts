/**
 * 公开资源的基础路径。
 * GitHub Pages 项目站点部署在 https://<用户>.github.io/<仓库名>/，
 * 构建时由 vite 的 base 注入 import.meta.env.BASE_URL（形如 "/buyi/"）。
 * 所有指向 public/ 的链接都必须经过这里 —— 否则相对路径会从站点根解析，
 * 部署后变成 404（本地 dev 是 "/" 所以看不出来，这是最容易漏的一类问题）。
 */
const BASE = import.meta.env.BASE_URL

/** 把 public/ 下的资源路径补成带 base 前缀的绝对路径 */
export function assetUrl(path: string): string {
  return `${BASE}${path.replace(/^\/+/, '')}`
}

